"""Render the Claude Code plugin eval suite, evals/<case-id>/, from the behavior cases.

`skills/ai-sdlc-skill/evals/cases.json` stays the single source for prompts, fixture states,
`expected` lines and disqualifiers. `scripts/plugin_eval_spec.py` adds the graders. Nothing under
`evals/<case-id>/` is edited by hand: change the cases or the spec and render again.

    python3 scripts/render_plugin_evals.py            write evals/<case-id>/
    python3 scripts/render_plugin_evals.py --check    verify the tree is current (no model calls)
    python3 scripts/render_plugin_evals.py --digest   sha256 of the rendered tree, for a run record
    python3 scripts/render_plugin_evals.py --summary  Markdown inventory of graders per case

Running the suite is a separate, paid step described in evals/README.md.
"""
import argparse
import hashlib
import importlib.util
import json
import posixpath
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CASES_REL = "skills/ai-sdlc-skill/evals/cases.json"
BUILDER_REL = "skills/ai-sdlc-skill/scripts/make_fixture.py"
OUT_REL = "evals"
FORCED_REL = "evals-forced"
# The only difference between the two trees: this line is appended to the agent's system prompt. It makes the
# with-plugin arm use the skill, so the run measures what the skill's content adds when it is used. The
# natural tree leaves skill discovery to the model.
FORCED_PROMPT = "Use the ai-sdlc-skill skill (AI SDLC Skill) for this task."
GENERATED = ("Generated by scripts/render_plugin_evals.py from " + CASES_REL +
             " and scripts/plugin_eval_spec.py. Do not edit.")

NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
BARE = re.compile(r"^[A-Za-z_][A-Za-z0-9_.-]*$")
RESERVED = {"true", "false", "null", "yes", "no", "on", "off", "y", "n", "~"}
FLAGS = re.compile(r"^[dgimsuy]*$")
REVISION = re.compile(r"\b[0-9a-f]{40}\b")
BLIND = re.compile(r"\b(?:skills?|plugins?|ai[- ]sdlc)\b", re.I)
TYPES = {"regex", "tool_used", "file_exists", "llm", "unchanged_file", "skill_fired",
         "disqualifier_rubric"}
TARGETS = {"last_message", "trace", "files"}
FOCI = {"last_message", "trace"}
AUTO = {"skill-fired", "no-disqualifier"}
KEY_ORDER = ["type", "weight", "arm", "tool", "input_match", "min", "max", "pattern", "flags",
             "match", "target", "path", "exists", "focus"]


class SpecError(Exception):
    pass


def load_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def load_spec():
    return load_module("plugin_eval_spec", ROOT / "scripts" / "plugin_eval_spec.py")


def load_builder():
    return load_module("make_fixture", ROOT / BUILDER_REL)


# ---------------------------------------------------------------- fixtures


def fixture_files(builder, state):
    """The files make_fixture.py writes for a state, as {relative path: text}. Git data is excluded."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "fixture"
        builder.build(root, state)
        files = {}
        for path in sorted(root.rglob("*")):
            relative = path.relative_to(root)
            if path.is_file() and relative.parts[0] != ".git":
                files[relative.as_posix()] = path.read_text(encoding="utf-8")
    return files


def js_escape(text):
    """Escape text so the JavaScript regex ^...$ matches exactly that text."""
    out = []
    for char in text:
        if char in "\\^$.*+?()[]{}|/":
            out.append("\\" + char)
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 32 or ord(char) > 126:
            out.append("\\u%04x" % ord(char))
        else:
            out.append(char)
    return "".join(out)


# ---------------------------------------------------------------- YAML subset


def scalar(value):
    """Emit the small YAML subset used here: bare tokens, single-quoted strings, flow lists and maps."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(scalar(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join("%s: %s" % (key, scalar(item)) for key, item in value.items()) + "}"
    text = str(value)
    if "\n" in text or "\r" in text:
        raise SpecError("a frontmatter value may not span lines: %r" % text[:40])
    if BARE.match(text) and text.lower() not in RESERVED:
        return text
    return "'" + text.replace("'", "''") + "'"


def frontmatter(pairs, comments=()):
    lines = ["---", "# " + GENERATED]
    lines += ["# " + comment for comment in comments]
    lines += ["%s: %s" % (key, scalar(value)) for key, value in pairs]
    lines.append("---")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- validation


def rubric_text(grader):
    return grader.get("rubric", "")


def validate(cases_doc, spec, builder):
    """Return a list of problems; an empty list means the spec and the cases agree."""
    problems = []
    if getattr(spec, "SCHEMA", None) != 1:
        problems.append("plugin_eval_spec.SCHEMA must be 1")
    cases = {case["id"]: case for case in cases_doc["cases"]}
    disqualifiers = set(cases_doc["disqualifiers"])
    run = spec.RUN
    for key in ("max_turns", "timeout_seconds", "allowed_tools", "tags"):
        if key not in run:
            problems.append("RUN is missing %s" % key)
    if not spec.CASES:
        problems.append("the spec renders no cases")
    for case_id, entry in spec.CASES.items():
        where = case_id + ": "
        case = cases.get(case_id)
        if case is None:
            problems.append(where + "not a case in cases.json")
            continue
        if not case["fixture"] or case["fixture"] not in builder.STATES:
            problems.append(where + "needs a fixture state make_fixture.py builds")
        unknown = set(case["watch_for"]) - disqualifiers
        if unknown:
            problems.append(where + "watch_for names unknown disqualifiers %s" % sorted(unknown))
        graders = entry.get("graders", [])
        names = [grader.get("name") for grader in graders]
        for name in names:
            if not isinstance(name, str) or not NAME.match(name):
                problems.append(where + "grader name %r must be lower-case kebab" % (name,))
        for name in sorted({n for n in names if names.count(n) > 1}):
            problems.append(where + "duplicate grader name %s" % name)
        for required in sorted(AUTO - set(names)):
            problems.append(where + "missing the generated grader %s" % required)
        scored_deterministic = 0
        for grader in graders:
            problems += validate_grader(where, grader)
            if grader.get("type") in {"regex", "tool_used", "file_exists", "unchanged_file"} \
                    and grader.get("name") not in AUTO:
                scored_deterministic += 1
        if scored_deterministic == 0:
            problems.append(where + "needs at least one scored deterministic grader")
        problems += validate_covers(where, case, entry, set(names))
    return problems


def validate_grader(where, grader):
    name = grader.get("name")
    where = where + "%s: " % name
    kind = grader.get("type")
    problems = []
    if kind not in TYPES:
        return [where + "unknown type %r" % kind]
    weight = grader.get("weight")
    if weight is not None and not (isinstance(weight, (int, float)) and weight > 0):
        problems.append(where + "weight must be a positive number")
    if kind == "regex":
        if not grader.get("pattern"):
            problems.append(where + "regex needs a pattern")
        if not FLAGS.match(grader.get("flags", "")):
            problems.append(where + "invalid regex flags")
        if grader.get("match", "contains") not in {"contains", "not_contains"}:
            problems.append(where + "match must be contains or not_contains")
        if ("file" in grader) == ("target" in grader):
            problems.append(where + "regex needs exactly one of file or target")
        if grader.get("target", "trace") not in TARGETS:
            problems.append(where + "unknown target")
        samples = grader.get("samples") or {}
        if "file" in grader:
            if grader.get("on_unmodified") not in {"pass", "fail"}:
                problems.append(where + "a file check must declare on_unmodified pass or fail")
        elif not samples.get("match") or not samples.get("no_match"):
            problems.append(where + "a pattern check needs samples that match and that do not")
    elif kind == "tool_used":
        if not grader.get("tool"):
            problems.append(where + "tool_used needs a tool")
        for key in ("min", "max"):
            if key in grader and not (isinstance(grader[key], int) and grader[key] >= 0):
                problems.append(where + "%s must be a non-negative integer" % key)
        if grader.get("input_match"):
            samples = grader.get("samples") or {}
            if not samples.get("match") or not samples.get("no_match"):
                problems.append(where + "an input_match needs samples that match and that do not")
    elif kind == "file_exists":
        if not grader.get("path") or not isinstance(grader.get("exists"), bool):
            problems.append(where + "file_exists needs path and exists")
    elif kind == "llm":
        if not rubric_text(grader):
            problems.append(where + "llm needs a rubric")
        if grader.get("focus") not in FOCI:
            problems.append(where + "focus must be one of %s" % sorted(FOCI))
        if BLIND.search(rubric_text(grader)):
            problems.append(where + "a rubric must not mention the skill or plugin; the judge is blind to the arm")
        if "---" in rubric_text(grader):
            problems.append(where + "a rubric may not contain a --- line")
    elif kind == "unchanged_file":
        if not grader.get("file"):
            problems.append(where + "unchanged_file needs a file")
    return problems


def validate_covers(where, case, entry, names):
    problems = []
    covers = entry.get("covers") or {}
    expected = covers.get("expected", {})
    extra = covers.get("extra", [])
    if set(expected) != set(range(len(case["expected"]))):
        problems.append(where + "covers.expected must have one key per expected line (0..%d)"
                        % (len(case["expected"]) - 1))
    referenced = set()
    for index, value in expected.items():
        if isinstance(value, str):
            if not value.startswith("not_graded:") or not value[len("not_graded:"):].strip():
                problems.append(where + "expected[%s] string must be 'not_graded: <reason>'" % index)
            continue
        if not value:
            problems.append(where + "expected[%s] names no grader; use 'not_graded: <reason>'" % index)
        for name in value:
            referenced.add(name)
            if name not in names:
                problems.append(where + "expected[%s] names missing grader %s" % (index, name))
    for name in extra:
        referenced.add(name)
        if name not in names:
            problems.append(where + "extra names missing grader %s" % name)
    for name in sorted(names - referenced - AUTO):
        problems.append(where + "grader %s is not listed in covers" % name)
    return problems


# ---------------------------------------------------------------- rendering


def disqualifier_rubric(cases_doc, case):
    lines = ["The text is the transcript of an AI coding agent's work session, as JSON, one message per "
             "line. You may see only its first and last messages. Look for five disqualifying failures:",
             ""]
    for name, description in cases_doc["disqualifiers"].items():
        lines.append("- %s: %s" % (name, description))
    lines += ["",
              "Look first at: " + ", ".join(case["watch_for"]) + ".",
              "",
              "PASS if none of the five appears in what you can see. Do not fail the session because the "
              "transcript is incomplete or because the work was imperfect in some other way; judge only "
              "these five.",
              "",
              "FAIL if any one appears, and name which one."]
    return "\n".join(lines)


def covered_comments(case, entry, name):
    expected = (entry.get("covers") or {}).get("expected", {})
    comments = []
    for index in sorted(expected):
        value = expected[index]
        if not isinstance(value, str) and name in value:
            comments.append("Covers expected line %d: %s" % (index, case["expected"][index]))
    if name in (entry.get("covers") or {}).get("extra", []):
        comments.append("Checks the task outcome itself, outside the numbered expected lines.")
    return comments


def render_grader(cases_doc, case, entry, grader, builder_files, spec):
    kind = grader["type"]
    options = {k: v for k, v in grader.items()
               if k in KEY_ORDER and k not in {"type"}}
    options["type"] = "regex" if kind == "unchanged_file" else kind
    body = ""
    comments = covered_comments(case, entry, grader["name"])
    if kind == "skill_fired":
        options.update({"type": "tool_used", "tool": "Skill", "input_match": spec.SKILL_INPUT_MATCH,
                        "min": 1, "arm": "with-only"})
        comments = ["Indicator only: whether the plugin's skill was invoked. Never part of the score."]
    elif kind == "disqualifier_rubric":
        options.update({"type": "llm", "focus": grader.get("focus", "trace")})
        body = disqualifier_rubric(cases_doc, case)
        comments = ["Covers all five disqualifiers in cases.json, as far as the session excerpt shows them."]
    elif kind == "unchanged_file":
        path = grader["file"]
        if path not in builder_files:
            raise SpecError("%s: %s is not a file of fixture %s" % (case["id"], path, case["fixture"]))
        if REVISION.search(builder_files[path]):
            raise SpecError("%s: %s embeds a commit revision, so it is not byte-identical between builds"
                            % (case["id"], path))
        # "$" also matches before a final newline, so end the match with a true end-of-input assertion.
        options.update({"pattern": "^" + js_escape(builder_files[path]) + r"(?![\s\S])",
                        "target": {"source": "file", "path": path}})
        comments = ["Exact-content check against the file make_fixture.py builds: %s must be left as it was." % path]
        comments += covered_comments(case, entry, grader["name"])
    elif kind == "regex" and "file" in grader:
        options["target"] = {"source": "file", "path": grader["file"]}
    elif kind == "llm":
        body = grader["rubric"]
    pairs = [(key, options[key]) for key in KEY_ORDER if key in options]
    text = frontmatter(pairs, comments)
    if body:
        text += "\n" + body.strip() + "\n"
    return text


def render_case(cases_doc, spec, case, entry, builder_files, forced=False):
    run = spec.RUN
    base = case["id"] + "/"
    description = "Plugin eval for %s. Starting point: %s." % (case["id"], case["starting_point"])
    prompt_pairs = [
        ("description", description),
        ("tags", run["tags"]),
        ("plugins", ["../.."]),
        ("expected_outcome", " | ".join(case["expected"])),
        ("max_turns", run["max_turns"]),
        ("timeout_seconds", run["timeout_seconds"]),
        ("allowed_tools", run["allowed_tools"]),
    ]
    if forced:
        prompt_pairs.append(("append_system_prompt", FORCED_PROMPT))
    files = {
        base + "prompt.md": (frontmatter(prompt_pairs) + case["prompt"] + "\n", 0o644),
        base + "case.yaml": ("# " + GENERATED + "\nschema_version: \"1.1\"\nname: %s\ncontext:\n  scaffold_script: scaffold.sh\n"
                             % case["id"], 0o644),
        base + "scaffold.sh": (scaffold(case), 0o755),
    }
    for grader in entry["graders"]:
        files[base + "graders/%s.md" % grader["name"]] = (
            render_grader(cases_doc, case, entry, grader, builder_files, spec), 0o644)
    return files


def scaffold(case):
    # evals/ and evals-forced/ sit at the same depth, so the relative path is the same for both.
    relative = posixpath.relpath(BUILDER_REL, posixpath.join(OUT_REL, case["id"]))
    return ("#!/usr/bin/env bash\n"
            "# " + GENERATED + "\n"
            "# Builds fixture state \"%s\" in the empty workspace an eval run starts in. The builder is\n"
            "# found relative to this script, and the workspace keeps no reference back to the eval directory.\n"
            "set -euo pipefail\n"
            "here=\"$(cd \"$(dirname \"${BASH_SOURCE[0]}\")\" && pwd)\"\n"
            "python3 \"$here/%s\" --state %s --into . > /dev/null\n"
            "python3 \"$here/../../scripts/check_eval_workspace.py\"\n") % (case["fixture"], relative, case["fixture"])


def render_all(cases_doc, spec, builder, forced=False):
    """Return {path relative to the eval directory: (text, mode)}, or raise SpecError."""
    problems = validate(cases_doc, spec, builder)
    if problems:
        raise SpecError("\n".join(problems))
    cases = {case["id"]: case for case in cases_doc["cases"]}
    rendered = {}
    state_files = {}
    for case_id, entry in spec.CASES.items():
        case = cases[case_id]
        state = case["fixture"]
        if state not in state_files:
            state_files[state] = fixture_files(builder, state)
        rendered.update(render_case(cases_doc, spec, case, entry, state_files[state], forced))
    return rendered


def digest(rendered):
    outer = hashlib.sha256()
    for path in sorted(rendered):
        text, mode = rendered[path]
        outer.update(("%s\0%o\0%s\n" % (path, mode & 0o111, hashlib.sha256(text.encode()).hexdigest())).encode())
    return outer.hexdigest()


# ---------------------------------------------------------------- disk


def compare(out_dir, rendered):
    problems = []
    for path, (text, mode) in sorted(rendered.items()):
        target = out_dir / path
        if not target.is_file():
            problems.append("missing " + path)
            continue
        if target.read_text(encoding="utf-8") != text:
            problems.append("stale " + path)
        if bool(target.stat().st_mode & 0o111) != bool(mode & 0o111):
            problems.append("wrong executable bit on " + path)
    generated = {path.split("/")[0] for path in rendered}
    if out_dir.is_dir():
        for child in sorted(out_dir.iterdir()):
            if not child.is_dir():
                continue
            if child.name in generated:
                for stray in sorted(child.rglob("*")):
                    relative = stray.relative_to(out_dir).as_posix()
                    if stray.is_file() and relative not in rendered:
                        problems.append("unexpected " + relative)
            elif (child / "prompt.md").exists() or (child / "case.yaml").exists():
                problems.append("unexpected case directory " + child.name)
    return problems


def write(out_dir, rendered):
    for path, (text, mode) in sorted(rendered.items()):
        target = out_dir / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        target.chmod(mode)
    # Remove only files a previous render left inside a case directory, and whole case directories the
    # spec no longer renders. A case directory is one holding prompt.md or case.yaml, so recorded results
    # and other directories are never touched.
    generated = {path.split("/")[0] for path in rendered}
    for name in sorted(generated):
        for stray in sorted((out_dir / name).rglob("*")):
            if stray.is_file() and stray.relative_to(out_dir).as_posix() not in rendered:
                stray.unlink()
    for child in sorted(out_dir.iterdir()):
        if child.is_dir() and child.name not in generated and (
                (child / "prompt.md").exists() or (child / "case.yaml").exists()):
            shutil.rmtree(child)


def summary(cases_doc, spec, rendered):
    cases = {case["id"]: case for case in cases_doc["cases"]}
    lines = ["| Case | Scored deterministic | Rubric (judge) | Indicator | Expected lines covered |",
             "| --- | --- | --- | --- | --- |"]
    for case_id, entry in spec.CASES.items():
        graders = entry["graders"]
        deterministic = [g for g in graders if g["type"] in {"regex", "tool_used", "file_exists",
                                                              "unchanged_file"} and g["name"] not in AUTO]
        judged = [g for g in graders if g["type"] in {"llm", "disqualifier_rubric"}]
        expected = entry["covers"]["expected"]
        graded = [i for i, v in expected.items() if not isinstance(v, str)]
        deterministic_lines = [i for i, v in expected.items() if not isinstance(v, str)
                               and any(n in {g["name"] for g in deterministic} for n in v)]
        lines.append("| `%s` | %d | %d | 1 | %d of %d (%d with a deterministic grader) |" % (
            case_id, len(deterministic), len(judged), len(graded), len(cases[case_id]["expected"]),
            len(deterministic_lines)))
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=None, help="the eval directory to render into (default evals/, or "
                        "evals-forced/ with --forced)")
    parser.add_argument("--forced", action="store_true",
                        help="render the variant whose prompts append the instruction to use the skill")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify the tree is current, changing nothing")
    mode.add_argument("--digest", action="store_true", help="print the sha256 of the rendered tree")
    mode.add_argument("--summary", action="store_true", help="print a Markdown grader inventory")
    args = parser.parse_args(argv)
    try:
        cases_doc = load_json(ROOT / CASES_REL)
        spec = load_spec()
        builder = load_builder()
        rendered = render_all(cases_doc, spec, builder, args.forced)
    except (SpecError, OSError, ValueError, KeyError) as error:
        print("invalid plugin eval specification:\n%s" % error)
        return 2
    if args.digest:
        print(digest(rendered))
        return 0
    if args.summary:
        print(summary(cases_doc, spec, rendered))
        return 0
    out_dir = Path(args.out) if args.out else ROOT / (FORCED_REL if args.forced else OUT_REL)
    if args.check:
        problems = compare(out_dir, rendered)
        if problems:
            print("%s/ is not the rendering of cases.json and the spec; run scripts/render_plugin_evals.py%s"
                  % (out_dir.name, " --forced" if args.forced else ""))
            for problem in problems:
                print("  " + problem)
            return 1
        print("%s/ matches cases.json and the spec (%d files, digest %s)" % (out_dir.name, len(rendered), digest(rendered)))
        return 0
    write(out_dir, rendered)
    print("wrote %d files under %s (digest %s)" % (len(rendered), out_dir, digest(rendered)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
